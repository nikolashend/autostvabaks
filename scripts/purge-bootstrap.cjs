#!/usr/bin/env node
/*
 * Builds public/assets/css/vendors/bootstrap.min.css from the full Bootstrap 5 stylesheet,
 * keeping only the selectors the public pages actually use (grid, modal, collapse, dropdown,
 * spinner, a handful of utilities) plus the classes Bootstrap's JS toggles at runtime.
 *
 * Usage (needs a Node environment with postcss + postcss-selector-parser, e.g. `npx`):
 *   node scripts/purge-bootstrap.cjs <path-to-full-bootstrap.min.css> <url1> [url2 ...]
 * Example:
 *   node scripts/purge-bootstrap.cjs vendor/bootstrap.min.css http://127.0.0.1:8010/ http://127.0.0.1:8010/ru \
 *        http://127.0.0.1:8010/en http://127.0.0.1:8010/kasutustingimused http://127.0.0.1:8010/does-not-exist
 * Set NODE_PATH to a node_modules folder that contains postcss if it is not installed locally.
 */
const fs = require('fs');
const path = require('path');
const postcss = require('postcss');
const selectorParser = require('postcss-selector-parser');

const [src, ...urls] = process.argv.slice(2);
if (!src || !urls.length) {
  console.error('usage: node scripts/purge-bootstrap.cjs <bootstrap.min.css> <url> [url...]');
  process.exit(1);
}

// classes added by Bootstrap JS / our JS after load (not present in server HTML)
const SAFELIST = [
  'show', 'showing', 'hiding', 'collapsing', 'collapse', 'fade', 'modal-open', 'modal-backdrop', 'modal-static',
  'dropdown-menu', 'dropdown-item', 'active', 'disabled', 'd-none', 'is-visible', 'is-stuck', 'is-open', 'is-invalid',
  'is-full', 'is-dragover', 'is-loaded', 'dropup', 'dropend', 'dropstart', 'modal', 'modal-dialog', 'modal-content',
  'modal-header', 'modal-body', 'modal-footer', 'modal-title', 'accordion', 'accordion-item', 'accordion-button',
  'accordion-collapse', 'accordion-header', 'accordion-body', 'spinner-border', 'spinner-border-sm', 'visually-hidden',
  'swiper-slide', 'swiper-wrapper', 'swiper-container',
];

async function collectClasses() {
  const used = new Set(SAFELIST);
  const re = /class="([^"]*)"/g;
  for (const url of urls) {
    const res = await fetch(url, { headers: { Accept: 'text/html' } });
    const html = await res.text();
    let m;
    while ((m = re.exec(html))) m[1].split(/\s+/).forEach((c) => c && used.add(c));
    console.error(`${url} → ${res.status}, ${used.size} classes so far`);
  }
  return used;
}

function selectorIsUsed(selector, used) {
  let ok = true;
  selectorParser((root) => {
    root.walkClasses((node) => { if (!used.has(node.value)) ok = false; });
  }).processSync(selector);
  return ok;
}

(async () => {
  const used = await collectClasses();
  const css = fs.readFileSync(src, 'utf8');
  const root = postcss.parse(css);
  let kept = 0, dropped = 0;

  root.walkRules((rule) => {
    if (rule.parent && rule.parent.type === 'atrule' && /keyframes/.test(rule.parent.name)) return;
    const selectors = rule.selectors.filter((s) => selectorIsUsed(s, used));
    if (!selectors.length) { rule.remove(); dropped++; return; }
    rule.selectors = selectors;
    kept++;
  });
  root.walkAtRules((at) => {
    if (/media|supports|layer/.test(at.name) && at.nodes && !at.nodes.length) at.remove();
  });

  const out = root.toString().replace(/^@charset "UTF-8";/, ''); // @charset must stay the very first token
  const dest = path.resolve(__dirname, '../public/assets/css/vendors/bootstrap.min.css');
  const header = `/*! Bootstrap v5.3 (MIT) – subset for autostvabaks.ee, generated by scripts/purge-bootstrap.cjs (${kept} rules kept, ${dropped} dropped). Regenerate from the full build after adding Bootstrap classes. */\n`;
  fs.writeFileSync(dest, '@charset "UTF-8";' + header + out);
  console.error(`written ${dest}: ${(header + out).length} bytes (from ${css.length})`);
})().catch((e) => { console.error(e); process.exit(1); });
